--- 字符表 -> { w, h, rows（布尔二维表，1-based） }
---@param table table
---@param h integer
---@return table
local function build(table, h)
    local out = {}
    for ch, src in pairs(table) do
        local rows = {}
        for row in src:gmatch("[^|]+") do
            local cells = {}
            for i = 1, #row do
                cells[i] = row:sub(i, i) == "#"
            end
            rows[#rows + 1] = cells
        end
        assert(#rows == h, string.format("字形 %s 有 %d 行，应为 %d", tostring(ch), #rows, h))
        out[ch] = { w = #rows[1], h = h, rows = rows }
    end
    return out
end

Font.FONTS = {
    mini = { h = 5, space = 2, gap = 1, glyphs = build(MINI, 5) },
    big = { h = 7, space = 3, gap = 1, glyphs = build(BIG, 7) },
}

--- 取字形（大小写回退，和原版一致）
---@param F table
---@param ch string
---@return table|nil
local function glyphOf(F, ch)
    local g = F.glyphs[ch]
    if g == nil then
        g = F.glyphs[ch:upper()]
    end
    return g
end

--- 字符串的像素宽（还没乘 scale）
---@param str string|number
---@param font string|nil "mini" | "big"
---@return integer
function Font.textWidth(str, font)
    local F = Font.FONTS[font or "mini"]
    local w = 0
    str = tostring(str)
    for i = 1, #str do
        local g = glyphOf(F, str:sub(i, i))
        w = w + (g and g.w or F.space) + F.gap
    end
    return math.max(0, w - F.gap)
end

--- 逐个着墨点回调 plot(x, y)，文字左上角在 (0, 0)
---@param str string|number
---@param font string
---@param plot fun(x: integer, y: integer)
function Font.rasterText(str, font, plot)
    local F = Font.FONTS[font or "mini"]
    local x = 0
    str = tostring(str)
    for i = 1, #str do
        local g = glyphOf(F, str:sub(i, i))
        if g == nil then
            x = x + F.space + F.gap
        else
            for r = 1, F.h do
                local cells = g.rows[r]
                for c = 1, g.w do
                    if cells[c] then
                        plot(x + c - 1, r - 1)
                    end
                end
            end
            x = x + g.w + F.gap
        end
    end
end

return Font
